//Neste desafio, vamos aprender sobre os vetores ("[]")! Podemos entender vetores uma espécie de “armários” que guardam vários valores em uma só variável ou...
//...constante ao mesmo tempo, de forma que não é necessário ficar declarando cada hora declarando uma diferente.

//No exemplo abaixo, guardamos diversos tipos de variáveis, como sendo classes de um personagem de um jogo

let classePersonagem = ["Cavaleiro", "Mago", "Bandido", "Feiticeiro"] //Aqui, estamos criando um vetor e atribuindo a ele as classes do personagem.

console.log(classePersonagem[0]) //Já aqui, estamos escolhendo uma classe para o personagem. O número zero dentro do colchete indica a posição do elemento determinado...
                                 //... que será exibido.
                                 // Nos vetores, a primeira posição sempre inicia-se com zero.