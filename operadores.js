//Neste desafio, vamos aprender sobre os operadores! Os operadores são símbolos que realizam todos os tipos de operações que conhecemos, como por exemplo soma (+)...
//e subtração (-).

//No exemplo abaixo, veremos exemplo de operadores, onde são criados e atribuídos valores a variáveis, para que sejam realizadas as operações.

//Atribuindo um valor inicial à variável
let numero1 = 15;
let numero2= 10;

//Soma
let resultadoSoma = numero1 + numero2; //Somando as duas variáveis criadas
console.log("Depois da soma (10 + 5):", resultadoSoma); // Saída: Depois da soma 15 + 10= 25

//Subtração
let resultadoSubtracao = numero1 - numero2;
console.log("Depois da subtração (13 - 7):", resultadoSubtracao); // Saída: Depois da subtração 15 - 10= 5
